def get_labels(business_type: str) -> dict[str, str]:
    """Get labels for a business type. Falls back to defaults for unknown types."""
    return LABELS.get(business_type, _DEFAULT)


def label(business_type: str, key: str) -> str:
    """Get a single label value."""
    return get_labels(business_type).get(key, _DEFAULT.get(key, key))
